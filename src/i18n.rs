/// 翻译一条静态界面文案；`zh` 同时是字典键。
pub fn t(zh: &'static str) -> &'static str {
    if is_en() {
        lookup(zh).unwrap_or(zh)
    } else {
        zh
    }
}

/// 英文计数短语（单复数）；只在英文模式使用。
pub fn n(count: usize, one: &'static str, many: &'static str) -> String {
    format!("{count} {}", if count == 1 { one } else { many })
}

/// 翻译运行时拼出的文案（例如后端/状态机返回的 String）。
pub fn owned(zh: String) -> String {
    if is_en() {
        lookup(&zh).map(str::to_string).unwrap_or(zh)
    } else {
        zh
    }
}

